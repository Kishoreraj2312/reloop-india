/**
 * Digital material passport (C1) — data model.
 *
 * A passport is a VIEW of one existing component, keyed by its stable record id: it is composed on demand from the model record
 * (A1–A3), the B1 quantities, the B2 assessment, the B3 removal plan, the B4 scenario outcomes and the B5 carbon assessment, and
 * stores nothing of those. The only data a passport owns is the user's own metadata (inspection status, observed condition,
 * notes, provenance). Every field says where it comes from and how reliable it is; a missing value is `null` with status
 * "missing", never a made-up value.
 */

import type { Unit } from "@/engine/quantities";

/** recorded: a value in the model's record (generated by A1–A3, whose confidence is "assumed"). calculated / estimated: B1. user: typed by the user. */
export type FieldStatus = "recorded" | "calculated" | "estimated" | "assumed" | "user" | "missing";
export type SourceTag = "model" | "B1" | "B2" | "B3" | "B4" | "B5" | "C2" | "C3" | "user";

export const STATUS_LABELS: Readonly<Record<FieldStatus, string>> = {
  recorded: "recorded",
  calculated: "calculated",
  estimated: "estimated",
  assumed: "assumed",
  user: "user entry",
  missing: "missing",
};

export interface Field {
  readonly key: string;
  readonly label: string;
  /** null = no value (status "missing"). Numbers are full precision; the UI formats them. */
  readonly value: string | number | null;
  readonly unit?: string;
  readonly status: FieldStatus;
  readonly source: SourceTag;
  /** Why the value is estimated / missing, or how it was derived. */
  readonly note?: string;
}

export const SECTION_KEYS = ["identity", "material", "quantity", "condition", "recovery", "removal", "sustainability", "provenance", "tracking"] as const;
export type SectionKey = (typeof SECTION_KEYS)[number];

export interface Section {
  readonly key: SectionKey;
  readonly title: string;
  readonly fields: readonly Field[];
}

export interface Passport {
  readonly found: true;
  readonly id: string;
  readonly kind: "component" | "assembly";
  readonly name: string;
  readonly sections: readonly Section[];
  /** How many fields have each status (the data-quality line of the passport). */
  readonly counts: Readonly<Record<FieldStatus, number>>;
  /** Cautions that apply to the passport as a whole. */
  readonly cautions: readonly string[];
}

/** A reference to an id that is not a component of the model: reported, never thrown. */
export interface MissingPassport {
  readonly found: false;
  readonly id: string;
  readonly reason: string;
}

// ── the user's own metadata ───────────────────────────────────────────────

export const INSPECTION_STATUSES = ["not_inspected", "scheduled", "inspected", "not_accessible"] as const;
export type InspectionStatus = (typeof INSPECTION_STATUSES)[number];
export const INSPECTION_LABELS: Readonly<Record<InspectionStatus, string>> = { not_inspected: "Not inspected", scheduled: "Inspection scheduled", inspected: "Inspected", not_accessible: "Not accessible" };

export const OBSERVED_CONDITIONS = ["good", "fair", "poor", "damaged"] as const;
export type ObservedCondition = (typeof OBSERVED_CONDITIONS)[number];
export const OBSERVED_LABELS: Readonly<Record<ObservedCondition, string>> = { good: "Good", fair: "Fair", poor: "Poor", damaged: "Damaged" };

export const MAX_NOTE = 2000;
export const MAX_SHORT = 120;

export interface PassportMeta {
  readonly inspectionStatus: InspectionStatus | null;
  /** The user's own observation. The model's `condition` is a generated default, not an observation. */
  readonly observedCondition: ObservedCondition | null;
  /** ISO date YYYY-MM-DD, or "". */
  readonly inspectedOn: string;
  readonly inspectedBy: string;
  readonly conditionNote: string;
  readonly provenanceNote: string;
  /** ISO timestamp of the last edit (set when an edit is applied). */
  readonly updatedAt: string | null;
}

export const EMPTY_META: PassportMeta = Object.freeze({ inspectionStatus: null, observedCondition: null, inspectedOn: "", inspectedBy: "", conditionNote: "", provenanceNote: "", updatedAt: null });
export type MetaPatch = Partial<Omit<PassportMeta, "updatedAt">>;
/** Sparse: only components the user has written about have an entry. */
export type MetaMap = ReadonlyMap<string, PassportMeta>;

export const isEmptyMeta = (m: PassportMeta): boolean =>
  m.inspectionStatus === null && m.observedCondition === null && m.inspectedOn === "" && m.inspectedBy === "" && m.conditionNote === "" && m.provenanceNote === "";

// ── injected inputs (computed by the scene layer from the existing stores) ──────────────

export interface RemovalStatus {
  readonly planName: string;
  /** 1-based step of the entry that stands for the component, or null when no entry does. */
  readonly step: number | null;
  readonly steps: number;
  readonly state: string | null;
  readonly blocked: boolean;
  /** The entry is an assembly that stands for this component. */
  readonly viaAssembly: string | null;
}

/** C3: where the component stands in recovery tracking (the engine's own summary, reduced to what a passport shows). */
export interface TrackingStatus {
  readonly stage: string;
  readonly stageAt: string;
  readonly unit: string;
  readonly planned: number | null;
  /** b2_estimate: B2 at the start of tracking; user: stated by the user; none: no planned quantity. */
  readonly plannedBasis: "b2_estimate" | "user" | "none";
  readonly recovered: number | null;
  readonly reused: number | null;
  readonly recycled: number | null;
  readonly disposed: number | null;
  readonly unrecovered: number | null;
  readonly inHand: number | null;
  readonly unaccounted: number | null;
  /** The weakest source among the recorded quantities. */
  readonly quality: "measured" | "estimated" | "assumed" | null;
  readonly flags: readonly string[];
  readonly events: number;
  readonly lastRecordedAt: string;
}

/** C2: a reuse allocation of this component and how much of it was recorded as actually reused (C3). */
export interface ReuseAllocationView {
  readonly requirement: string;
  readonly quantity: number;
  readonly unit: string;
  readonly reused: number;
}

export interface ScenarioOutcome {
  readonly scenario: string;
  readonly unit: Unit;
  readonly quantity: number | null;
  /** Outcome quantities in `unit`, or null when the component has no quantity. */
  readonly outcome: Readonly<Record<"direct_reuse" | "refurbish_reuse" | "recycling" | "disposal" | "unknown", number>> | null;
  /** Why the outcome is unknown or not configured, when B4 says so. */
  readonly missing: string | null;
}
